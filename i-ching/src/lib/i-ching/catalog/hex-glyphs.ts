/** King Wen font glyph for hexagram number 1–64. */
export function hexGlyph(hexagramNumber: number): string {
	if (hexagramNumber < 1 || hexagramNumber > 64) return '';
	return HEX_GLYPHS[hexagramNumber] ?? '';
}
